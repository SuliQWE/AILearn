import { Part } from "./gemini";

export const CONTENT_SYSTEM = `Ты — опытный школьный методист. Пиши на русском языке, просто и точно.
Строгие правила:
- Опирайся ТОЛЬКО на предоставленный материал и общеизвестные школьные факты по теме урока.
- НЕ выдумывай ссылки, цитаты, даты, цифры, источники и имена. Если уверенности нет — не включай факт.
- Интернет-поиск недоступен, внешних ссылок не давай.
- Верни ТОЛЬКО JSON без пояснений.`;

export function contentPrompt(opts: { topic?: string | null; grade?: string | null; subject?: string | null; instructions?: string | null; materialText?: string }): Part[] {
  const grade = opts.grade ? `Класс/уровень учеников: ${opts.grade}.` : "Уровень: средняя школа.";
  const subject = opts.subject ? `Предмет: ${opts.subject}.\n` : "";
  const wishes = opts.instructions ? `\nПожелания учителя (обязательно учти): ${opts.instructions.slice(0, 2000)}\n` : "";
  const text = `Составь материалы для урока.
${subject}Тема: ${opts.topic || "(определи тему по приложенному материалу)"}
${grade}${wishes}
${opts.materialText ? `\nМатериал учителя:\n"""\n${opts.materialText.slice(0, 60000)}\n"""\n` : ""}
Формат JSON (строго):
{
  "explanation": "понятное объяснение темы простыми словами, 150-300 слов, абзацы разделяй \\n\\n",
  "examples": ["2-4 коротких примера из жизни или школьной практики"],
  "questions": [ // РОВНО 6 вопросов с одним верным ответом
    {"topic": "краткая подтема для повторения", "q": "вопрос", "options": ["A","B","C","D"], "correct": 0}
  ],
  "open_questions": [ // РОВНО 2
    {"q": "открытый вопрос", "hint": "подсказка учителю: что должно быть в хорошем ответе"}
  ],
  "tasks": [ // РОВНО 2 практические задачи, решаются письменно на бумаге за ~15 минут на обе
    {"title": "название", "text": "условие задачи"}
  ],
  "retell_prompt": "что ученику подготовить для устного пересказа (1-2 предложения)",
  "formulas": [ // 0-6. ОБЯЗАТЕЛЬНО заполни, если в теме есть формулы, уравнения, законы, правила или схемы записи (математика, физика, химия, информатика…): дискриминант, теорема Пифагора, закон Ома, уравнение реакции и т.п.
    {"title": "название формулы", "latex": "корректный LaTeX БЕЗ знаков $, например D = b^2 - 4ac", "notebook": "как записать в тетрадь: 2-5 коротких шагов через \\n — что написать, с какой строки, что означают буквы", "example": "короткий пример подстановки (формулы внутри $...$)"}
  ],
  "extra_materials": [ // 0-3 дополнительных блока (глоссарий, разбор типичной ошибки), только из материала и темы
    {"title": "заголовок", "text": "текст"}
  ]
}
Для нематематических тем без формул поле "formulas" — пустой массив [].
Все формулы в explanation, examples, вопросах и задачах пиши в LaTeX между $...$ (например $D=b^2-4ac$, $x_{1,2}=\\frac{-b\\pm\\sqrt{D}}{2a}$). В JSON каждый обратный слэш экранируй (\\\\frac).
Поле "correct" — индекс верного варианта (0-3). Верные ответы распредели по разным позициям. Неверные варианты должны быть правдоподобными.`;
  return [{ text }];
}
